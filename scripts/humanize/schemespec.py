"""Numbering-scheme specification (Kabat / IMGT).

Single source of truth for every *position-space* constant the engine needs.
The Kabat instance is built directly from ``config`` (never duplicated); the
IMGT instance's position sets are loaded from
``data/germline/kabat_imgt_positions.json`` (generated by
``scripts/build_imgt_positions.py`` from the paired germline files).

Constants covered:
  * J anchor (FR4 start) per chain
  * FR region tables for donor<->germline correspondence (fr_indel)
  * literature position sets: vernier / interface / canonical / CVI,
    VHH hallmark, empirical no-effect
  * CDR3 stem numbers (loop residues mislabelled FR3 in strict Kabat)
  * CDR graft windows per (numbering, cdr-scheme)

Rule: a pipeline run uses exactly ONE numbering space; never mix specs.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from typing import Dict, Optional, Tuple

from . import config

_VALID = ("kabat", "imgt")

# FR region tables used by fr_indel donor<->germline pairing.
# Kabat values mirror fr_indel.FR_REGIONS_*; IMGT values are the Lefranc
# region boundaries (H and L share the same IMGT numbering).
_FR_REGIONS: Dict[str, Dict[str, Tuple[Tuple[str, int, int], ...]]] = {
    "kabat": {
        "H": (("FR1", 1, 30), ("FR2", 36, 49), ("FR3", 66, 92)),
        "L": (("FR1", 1, 23), ("FR2", 35, 49), ("FR3", 57, 88)),
    },
    "imgt": {
        "H": (("FR1", 1, 26), ("FR2", 39, 55), ("FR3", 66, 104)),
        "L": (("FR1", 1, 26), ("FR2", 39, 55), ("FR3", 66, 104)),
    },
}

_J_ANCHOR = {"kabat": {"H": 103, "L": 98}, "imgt": {"H": 118, "L": 118}}

# Loop residues that strict Kabat labels FR3 (93/94) but which must never be
# back-mutation candidates; IMGT labels them CDR3 natively (105/106).
_CDR3_STEM = {"kabat": {"H": (93, 94), "L": ()},
              "imgt": {"H": (105, 106), "L": (105, 106)}}

# Native IMGT CDR graft windows (both chains; IMGT numbering is shared).
_IMGT_CDR_WINDOWS = {
    "H": {"CDR1": (27, 38), "CDR2": (56, 65), "CDR3": (105, 117)},
    "L": {"CDR1": (27, 38), "CDR2": (56, 65), "CDR3": (105, 117)},
}

_JSON_PATH = os.path.join(os.path.dirname(os.path.dirname(__file__)),
                          "..", "data", "germline", "kabat_imgt_positions.json")


def _frozen_sets(d) -> Dict[str, frozenset]:
    return {k: frozenset(v) for k, v in d.items()}


@dataclass(frozen=True)
class SchemeSpec:
    numbering: str                                # "kabat" | "imgt"
    j_anchor: Dict[str, int]                      # {"H": ..., "L": ...}
    fr_regions: Dict[str, Tuple[Tuple[str, int, int], ...]]
    vernier: Dict[str, frozenset]
    interface_core: Dict[str, frozenset]
    interface_extended: Dict[str, frozenset]
    canonical: Dict[str, frozenset]
    cvi: Dict[str, frozenset]                     # union of the four above
    vhh_hallmark: frozenset
    empirical_no_effect: Dict[str, frozenset]
    cdr3_stem: Dict[str, frozenset]
    translation_note: str = ""

    # -- membership helpers -------------------------------------------------
    def is_vhh_hallmark(self, num: int) -> bool:
        return num in self.vhh_hallmark

    def in_cvi(self, chain_type: str, num: int) -> bool:
        return num in self.cvi.get(chain_type, frozenset())

    def is_vernier(self, chain_type: str, num: int) -> bool:
        return num in self.vernier.get(chain_type, frozenset())

    def is_interface(self, chain_type: str, num: int) -> bool:
        s = self.interface_core.get(chain_type, frozenset()) | \
            self.interface_extended.get(chain_type, frozenset())
        return num in s

    def is_interface_core(self, chain_type: str, num: int) -> bool:
        return num in self.interface_core.get(chain_type, frozenset())

    def is_canonical(self, chain_type: str, num: int) -> bool:
        return num in self.canonical.get(chain_type, frozenset())

    def is_empirical_no_effect(self, chain_type: str, num: int) -> bool:
        return num in self.empirical_no_effect.get(chain_type, frozenset())

    def in_fr_region(self, chain_type: str, num: int) -> Optional[str]:
        """FR1/FR2/FR3 name for the number, else None (CDR/J/indel)."""
        for name, lo, hi in self.fr_regions[chain_type]:
            if lo <= num <= hi:
                return name
        return None

    def j_anchor_for(self, chain_type: str) -> int:
        return self.j_anchor[chain_type]


def _union(sets: Dict[str, Dict[str, frozenset]]) -> Dict[str, frozenset]:
    chains = set()
    for s in sets.values():
        chains |= set(s)
    return {c: frozenset().union(*(s.get(c, frozenset()) for s in sets.values()))
            for c in chains}


def _load_imgt_sets() -> tuple:
    with open(_JSON_PATH) as fh:
        blob = json.load(fh)
    sets = blob["sets"]
    note = (f"kabat_imgt_positions.json v{blob['version']} "
            f"({blob['paired_genes']} genes, threshold {blob['threshold']})")
    return sets, note


def get_spec(numbering: str = "kabat") -> SchemeSpec:
    """Return the (cached) SchemeSpec for a numbering space."""
    if numbering not in _VALID:
        raise ValueError(f"unknown numbering scheme: {numbering!r} "
                         f"(expected one of {_VALID})")
    spec = _CACHE.get(numbering)
    if spec is not None:
        return spec

    if numbering == "kabat":
        sets = {
            "VERN": _frozen_sets({c: s for c, s in config.VERNIER_ZONE.items()}),
            "CORE": _frozen_sets(config.INTERFACE_CORE),
            "EXT": _frozen_sets(config.INTERFACE_EXTENDED),
            "CAN": _frozen_sets(config.CANONICAL),
        }
        hallmark = frozenset(config.VHH_HALLMARK)
        empirical = _frozen_sets(config.EMPIRICAL_NO_EFFECT)
        note = "kabat: values from scripts/humanize/config.py"
    else:
        raw, note = _load_imgt_sets()
        sets = {
            "VERN": _frozen_sets(raw["VERNIER_ZONE"]),
            "CORE": _frozen_sets(raw["INTERFACE_CORE"]),
            "EXT": _frozen_sets(raw["INTERFACE_EXTENDED"]),
            "CAN": _frozen_sets(raw["CANONICAL"]),
        }
        hallmark = frozenset(raw["VHH_HALLMARK"])
        empirical = _frozen_sets({c: v for c, v in raw["EMPIRICAL_NO_EFFECT"].items() if v})

    spec = SchemeSpec(
        numbering=numbering,
        j_anchor=dict(_J_ANCHOR[numbering]),
        fr_regions={c: tuple(t) for c, t in _FR_REGIONS[numbering].items()},
        vernier=sets["VERN"],
        interface_core=sets["CORE"],
        interface_extended=sets["EXT"],
        canonical=sets["CAN"],
        cvi=_union({"a": sets["VERN"], "b": sets["CORE"],
                    "c": sets["EXT"], "d": sets["CAN"]}),
        vhh_hallmark=hallmark,
        empirical_no_effect=empirical,
        cdr3_stem=_frozen_sets({c: list(v) for c, v in _CDR3_STEM[numbering].items()}),
        translation_note=note,
    )
    _CACHE[numbering] = spec
    return spec


def cdr_windows(numbering: str, scheme: str) -> Dict[str, Dict[str, tuple]]:
    """CDR graft windows for (numbering, cdr-scheme).

    Kabat numbering keeps the four legacy schemes defined over the Kabat
    backbone (graft.CDR_POS_SETS). IMGT numbering uses the native IMGT
    windows and only accepts scheme="imgt".
    """
    if numbering == "imgt":
        if scheme != "imgt":
            raise ValueError(
                f"--numbering imgt requires CDR scheme 'imgt' (got {scheme!r})")
        return {c: dict(w) for c, w in _IMGT_CDR_WINDOWS.items()}
    if scheme not in ("kabat", "chothia", "abm", "imgt"):
        raise ValueError(f"unknown CDR scheme: {scheme!r}")
    from .graft import CDR_POS_SETS  # deferred: graft imports this module
    return CDR_POS_SETS[scheme]


_CACHE: Dict[str, SchemeSpec] = {}
